import { createHash } from "node:crypto";
import { generateText } from "ai";
import { eq } from "drizzle-orm";
import { api, config } from "keryx";
// Type-only, purely for the `declare module "keryx"` augmentation inside.
import type {} from "../config/mcp";
import { type Bot, bots } from "../schema/bots";
import { type BotServer, botServers, catalogHash } from "./McpCatalogOps";
import { languageModel } from "./ModelOps";

/**
 * A bot's **capabilities**: a few lines saying what its MCP tools can do,
 * grouped by theme and without tool names, so the model searches for a tool
 * instead of guessing one. Generated by the bot's `fast` model whenever the
 * catalog it can see changes, stored on the bot, and read by the prompt
 * assembler — so the prompt stays a pure function of stored rows.
 */

/** The most a summary may hold. */
const MAX_CHARS = 2_000;

/**
 * The digest of what a summary is generated from: each server's name and
 * catalog, and whether a model writes it.
 * @param servers - The bot's servers.
 * @returns The hex digest.
 */
export function capabilitiesInputHash(servers: BotServer[]): string {
  return createHash("sha256")
    .update(
      JSON.stringify({
        generated: config.mcp.generateCapabilities,
        servers: servers.map((s) => [
          s.server.name,
          catalogHash(s.server.toolsCache),
        ]),
      }),
    )
    .digest("hex");
}

/**
 * The summary written without a model: each server and how many tools it has.
 * @param servers - The bot's servers.
 * @returns The text.
 */
export function plainCapabilities(servers: BotServer[]): string {
  return servers
    .map(
      (s) =>
        `- ${s.server.name}: ${s.server.toolsCache.length} tool${s.server.toolsCache.length === 1 ? "" : "s"}`,
    )
    .join("\n");
}

/**
 * Ask the bot's `fast` model for a thematic summary of its tools.
 * @param bot - The bot.
 * @param servers - Its servers.
 * @returns The summary.
 */
async function generatedCapabilities(
  bot: Bot,
  servers: BotServer[],
): Promise<string> {
  const catalog = servers
    .map(
      (s) =>
        `Server ${s.server.name}:\n${s.server.toolsCache
          .map((t) => `- ${t.title ?? t.name}: ${t.description.slice(0, 300)}`)
          .join("\n")}`,
    )
    .join("\n\n");
  const fast = await languageModel(bot.projectId, bot.fastModelAlias);
  const { text } = await generateText({
    model: fast.model,
    system:
      "You summarize what a set of tools lets an assistant do. Write at most eight short markdown bullets, grouped by theme (for example: email, calendars, code review). Say what can be read and what can be changed. Never write a tool's name or a server's name; describe abilities in plain words.",
    prompt: catalog,
    maxRetries: 2,
  });
  const names = servers.flatMap((s) => s.server.toolsCache.map((t) => t.name));
  let out = text.trim().slice(0, MAX_CHARS);
  // A name with an underscore or dash is a tool name, never a plain word.
  for (const name of names) {
    if (/[_-]/.test(name)) out = out.replaceAll(name, "a tool");
  }
  return out;
}

/**
 * Regenerate a bot's capabilities when what they describe changed. Never
 * throws for a model failure: the plain summary stands in, and the next
 * change tries again.
 * @param botId - The bot.
 * @returns Whether the stored summary changed.
 */
export async function regenerateCapabilities(botId: number): Promise<boolean> {
  const [bot] = await api.db.db.select().from(bots).where(eq(bots.id, botId));
  if (!bot) return false;
  const servers = (await botServers(api.db.db, botId)).filter(
    (s) => s.server.toolsCache.length > 0,
  );
  const bound = (await botServers(api.db.db, botId)).length > 0;
  if (!bound) {
    if (bot.capabilities === null && bot.capabilitiesHash === null)
      return false;
    await api.db.db
      .update(bots)
      .set({ capabilities: null, capabilitiesHash: null })
      .where(eq(bots.id, botId));
    return true;
  }
  const hash = capabilitiesInputHash(servers);
  if (hash === bot.capabilitiesHash) return false;
  let text = plainCapabilities(servers);
  let stored = hash;
  if (config.mcp.generateCapabilities && servers.length > 0) {
    try {
      text = await generatedCapabilities(bot, servers);
    } catch (error) {
      // The plain list stands in; a null hash lets the next run try again.
      stored = `plain:${hash}`;
      api.logger.warn("could not generate a bot's capabilities", {
        botId,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }
  await api.db.db
    .update(bots)
    .set({ capabilities: text, capabilitiesHash: stored })
    .where(eq(bots.id, botId));
  return true;
}
