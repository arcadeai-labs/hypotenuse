import { sql } from "drizzle-orm";
import {
  customType,
  index,
  integer,
  pgTable,
  serial,
  text,
  timestamp,
  vector,
} from "drizzle-orm/pg-core";
import { memoryDocuments } from "./memory_documents";

/**
 * The size of every stored embedding. A deployment constant: the column is
 * `vector(1536)`, so changing it is a migration. An embedding model whose
 * native size differs must accept a `dimensions` option, which the embedding
 * alias's probe proves before the alias is saved.
 */
export const MEMORY_EMBEDDING_DIMENSIONS = 1536;

/** A Postgres `tsvector`, only ever generated by the database. */
const tsvector = customType<{ data: string }>({
  dataType: () => "tsvector",
});

/**
 * A `memory_chunk` is one piece of a **current** memory version: what search
 * ranks. `searchText` (path, description, heading breadcrumb, then the body)
 * is what both the embedding and the generated `tsv` are computed from, so a
 * query naming a path or a heading finds the chunk.
 *
 * A write commits its chunks with a null `embedding`; `memory:embed` fills it
 * in later and stamps `embeddingRevision`. A chunk whose revision is not the
 * project's current one is stale, and is ranked by keyword alone until
 * re-embedded. Chunks of a version that stops being current are deleted with
 * the write that replaced it; the version's content stays readable.
 *
 * `projectId` is copied from the document so the embed sweep can find a
 * project's work without a join.
 */
export const memoryChunks = pgTable(
  "memory_chunks",
  {
    id: serial("id").primaryKey(),
    documentId: integer("document_id")
      .notNull()
      .references(() => memoryDocuments.id, { onDelete: "cascade" }),
    projectId: integer("project_id").notNull(),
    chunkIndex: integer("chunk_index").notNull(),
    breadcrumb: text("breadcrumb").notNull().default(""),
    body: text("body").notNull(),
    searchText: text("search_text").notNull(),
    tsv: tsvector("tsv")
      .notNull()
      .generatedAlwaysAs(sql`to_tsvector('english', search_text)`),
    embedding: vector("embedding", {
      dimensions: MEMORY_EMBEDDING_DIMENSIONS,
    }),
    embeddingRevision: text("embedding_revision"),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index("memory_chunks_document_idx").on(t.documentId),
    index("memory_chunks_project_revision_idx").on(
      t.projectId,
      t.embeddingRevision,
    ),
    index("memory_chunks_tsv_idx").using("gin", t.tsv),
    index("memory_chunks_embedding_idx").using(
      "hnsw",
      t.embedding.op("vector_cosine_ops"),
    ),
  ],
);

export type MemoryChunk = typeof memoryChunks.$inferSelect;
export type NewMemoryChunk = typeof memoryChunks.$inferInsert;
