import {
  boolean,
  customType,
  integer,
  jsonb,
  numeric,
  pgTable,
  serial,
  text,
  timestamp,
  uniqueIndex,
  varchar,
} from "drizzle-orm/pg-core";
import type { EncryptedSecret } from "../ops/CryptoOps";
import { projects } from "./projects";
import { users } from "./users";

/** A Postgres `bytea`, read and written as a `Buffer`. */
const bytea = customType<{ data: Buffer; driverData: Buffer }>({
  dataType: () => "bytea",
});

/**
 * A `bot` is one agent of a project: who it is (name, display name, avatar;
 * its persona is the *Identity* section of its prompt, in `prompt_sections`), which of the project's model aliases it thinks with, who may read
 * and change it, whom it asks for help, and what it may spend.
 *
 * - `slug` is unique per project. It becomes **immutable once the bot has any
 *   platform installation**, because the Slack and Linear app manifests
 *   generated for it embed it; that rule is enforced by the platform
 *   installation code, which does not exist yet.
 * - `avatar` is stored, not linked: a platform app's icon is uploaded by a
 *   person from the generated manifest's instructions, and the dashboard must
 *   not depend on a third-party URL staying up. Never serialized; served by
 *   `bot:avatar`.
 * - `modelAlias` / `fastModelAlias` name `model_aliases` rows by name, not by
 *   id, so an alias can be repointed without touching any bot.
 * - `accessRead` / `accessWrite` are tag-name lists, read only through
 *   `AccessOps` (`canReadBot` / `canWriteBot`).
 * - `helpNotifyTag` null means the project's admins.
 * - `monthlyBudgetUsd` stops a bot for the month once the cost its provider
 *   reports reaches it (`CostOps.budgetExceeded`); unpriced calls count nothing.
 * - `enabled` false means the bot accepts no new conversations.
 * - `maxStepsPerTurn` bounds one turn of the agent loop: a turn that takes
 *   more model steps fails, saying how many it took.
 * - `memoryChannelHalfLifeDays` / `memoryProjectHalfLifeDays` — how fast a
 *   memory fades in this bot's search ranking: an unused channel memory loses
 *   half its weight every 30 days by default, a project memory every 180. The
 *   decay clock also tombstones channel memory that has faded past use.
 * - `apiCallbackSecret` signs the API channel's callbacks. Sealed with
 *   `CryptoOps`, shown once by `bot:rotate-callback-secret`, never serialized.
 * - `approverTag` — who may decide this bot's tool-call approvals besides the
 *   people who may write it; null means only they. `approvalTtlSeconds` is how
 *   long an approval waits before it expires (and reads as denied).
 * - `promptBudgetTokens` — the system prompt's size budget, estimated at four
 *   characters a token. Contextual sections are dropped to fit it; a change
 *   that would make the always-included text exceed it is refused.
 * - `maxAgentSections` — how many sections the bot may create itself with
 *   `prompt_create`.
 * - `capabilities` — what the bot's MCP tools can do, in themes and without
 *   tool names, generated by its `fast` model whenever its catalog changes;
 *   `capabilitiesHash` is the digest of the catalog it was generated from.
 *   Null when the bot has no MCP servers.
 */
export const bots = pgTable(
  "bots",
  {
    id: serial("id").primaryKey(),
    projectId: integer("project_id")
      .notNull()
      .references(() => projects.id, { onDelete: "cascade" }),
    name: varchar("name", { length: 80 }).notNull(),
    slug: varchar("slug", { length: 64 }).notNull(),
    description: varchar("description", { length: 280 }).notNull().default(""),
    displayName: varchar("display_name", { length: 80 }).notNull(),
    avatar: bytea("avatar"),
    avatarMimeType: text("avatar_mime_type"),
    modelAlias: varchar("model_alias", { length: 64 })
      .notNull()
      .default("default"),
    fastModelAlias: varchar("fast_model_alias", { length: 64 })
      .notNull()
      .default("fast"),
    accessRead: jsonb("access_read").$type<string[]>().notNull().default([]),
    accessWrite: jsonb("access_write").$type<string[]>().notNull().default([]),
    helpNotifyTag: varchar("help_notify_tag", { length: 256 }),
    monthlyBudgetUsd: numeric("monthly_budget_usd", {
      precision: 10,
      scale: 2,
    }),
    enabled: boolean("enabled").notNull().default(true),
    maxStepsPerTurn: integer("max_steps_per_turn").notNull().default(50),
    memoryChannelHalfLifeDays: integer("memory_channel_half_life_days")
      .notNull()
      .default(30),
    memoryProjectHalfLifeDays: integer("memory_project_half_life_days")
      .notNull()
      .default(180),
    apiCallbackSecret: jsonb("api_callback_secret").$type<EncryptedSecret>(),
    approverTag: varchar("approver_tag", { length: 256 }),
    approvalTtlSeconds: integer("approval_ttl_seconds")
      .notNull()
      .default(86_400),
    promptBudgetTokens: integer("prompt_budget_tokens")
      .notNull()
      .default(8_000),
    maxAgentSections: integer("max_agent_sections").notNull().default(10),
    capabilities: text("capabilities"),
    capabilitiesHash: text("capabilities_hash"),
    createdByUserId: integer("created_by_user_id").references(() => users.id, {
      onDelete: "set null",
    }),
    createdAt: timestamp("created_at", { withTimezone: true })
      .notNull()
      .defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true })
      .notNull()
      .defaultNow()
      .$onUpdateFn(() => new Date()),
  },
  (t) => [uniqueIndex("bots_project_slug_idx").on(t.projectId, t.slug)],
);

export type Bot = typeof bots.$inferSelect;
export type NewBot = typeof bots.$inferInsert;
