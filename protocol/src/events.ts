import { z } from "zod";

/** The most events one `daemon:events` call carries. */
export const MAX_EVENTS_PER_BATCH = 100;

/** The largest `daemon:events` body, in bytes. */
export const MAX_EVENTS_BATCH_BYTES = 256 * 1024;

/** The `error.type` of the 409 for an item this runner does not hold. */
export const NOT_YOUR_WORK = "NOT_YOUR_WORK";

/** The `error.type` of the 409 for a batch whose `seq` goes backwards. */
export const SEQ_REGRESSION = "SEQ_REGRESSION";

/** Markdown, as every `body` is. */
const body = z
  .string()
  .trim()
  .min(1)
  .max(64 * 1024);

/** What every event carries. */
const envelope = {
  eventId: z
    .uuid({ version: "v4" })
    .describe(
      "Generated by the daemon; the idempotency key end to end (the Linear activity's client id)",
    ),
  seq: z
    .number()
    .int()
    .positive()
    .describe("Per work item, from 1, never going backwards"),
  at: z.number().int().describe("When the daemon saw it, epoch ms"),
};

/** A `select` elicitation's options. */
export const SelectMetadata = z.strictObject({
  options: z
    .array(
      z.strictObject({
        label: z.string().trim().min(1).max(255).optional(),
        value: z.string().trim().min(1).max(1024),
      }),
    )
    .min(1)
    .max(25),
});

/**
 * What a login is needed for, as a runner auth page's path segment: an agent
 * id, `github`, or a git host.
 */
export const AuthProvider = z
  .string()
  .regex(/^[a-z0-9][a-z0-9._-]{0,63}$/)
  .describe("An agent id, `github`, or a git host");

/**
 * An `auth` elicitation's link. A daemon names the `provider` and the server
 * links the runner's auth page for it (`/runners/<id>/auth/<provider>`) — the
 * login has to happen on the runner's machine. A `url` is passed through
 * only when it is a public `https` link (an agent's own URL login); the
 * server sets `userId` itself, to the person who can fix it.
 */
export const AuthMetadata = z
  .strictObject({
    url: z.url().optional(),
    provider: AuthProvider.optional(),
    userId: z.string().max(255).optional(),
    providerName: z.string().max(255).optional(),
  })
  .refine((m) => m.url !== undefined || m.provider !== undefined, {
    message: "an auth elicitation needs a url or a provider",
  });

/** The agent is thinking. */
export const ThoughtEvent = z.strictObject({
  ...envelope,
  type: z.literal("thought"),
  body,
  ephemeral: z.boolean().default(false),
});

/** The agent did (or is doing) something. */
export const ActionEvent = z.strictObject({
  ...envelope,
  type: z.literal("action"),
  action: z.string().trim().min(1).max(255),
  parameter: z.string().trim().min(1).max(4096),
  result: z
    .string()
    .max(64 * 1024)
    .optional(),
  ephemeral: z.boolean().default(false),
});

/** The agent needs a person. `signal` is checked against its metadata. */
export const ElicitationEvent = z
  .strictObject({
    ...envelope,
    type: z.literal("elicitation"),
    body,
    signal: z.enum(["select", "auth"]).optional(),
    signalMetadata: z.record(z.string(), z.unknown()).optional(),
  })
  .superRefine((event, ctx) => {
    if (!event.signal) {
      if (event.signalMetadata) {
        ctx.addIssue({
          code: "custom",
          message: "signalMetadata needs a signal",
          path: ["signalMetadata"],
        });
      }
      return;
    }
    const schema = event.signal === "select" ? SelectMetadata : AuthMetadata;
    const parsed = schema.safeParse(event.signalMetadata);
    if (!parsed.success) {
      ctx.addIssue({
        code: "custom",
        message: `signalMetadata is not a valid ${event.signal} payload`,
        path: ["signalMetadata"],
      });
    }
  });

/** The turn's answer. */
export const ResponseEvent = z.strictObject({
  ...envelope,
  type: z.literal("response"),
  body,
});

/** The turn failed. */
export const ErrorEvent = z.strictObject({
  ...envelope,
  type: z.literal("error"),
  body,
});

/** The plan's step statuses, in ACP's spelling. */
export const PLAN_ENTRY_STATUSES = [
  "pending",
  "in_progress",
  "completed",
  "canceled",
] as const;

/** The whole plan, replaced on every event. */
export const PlanEvent = z.strictObject({
  ...envelope,
  type: z.literal("plan"),
  entries: z
    .array(
      z.strictObject({
        content: z.string().trim().min(1).max(1024),
        status: z.enum(PLAN_ENTRY_STATUSES),
      }),
    )
    .max(100),
});

/** The session's title: one line of 1–255 characters. */
export const SummaryEvent = z.strictObject({
  ...envelope,
  type: z.literal("summary"),
  title: z
    .string()
    .min(1)
    .max(255)
    .regex(/^[^\r\n\0]*$/, "one line")
    .refine((t) => t.trim().length > 0, "not blank"),
});

/** A link to show on the session (a pull request, say). */
export const ExternalUrlEvent = z.strictObject({
  ...envelope,
  type: z.literal("external_url"),
  label: z.string().trim().min(1).max(255),
  url: z.url(),
});

/** Token and cost accounting, for the dashboard only. */
export const UsageEvent = z.strictObject({
  ...envelope,
  type: z.literal("usage"),
  inputTokens: z.number().int().min(0).optional(),
  outputTokens: z.number().int().min(0).optional(),
  costUsd: z.number().min(0).optional(),
  contextUsed: z.number().int().min(0).optional(),
  contextSize: z.number().int().min(0).optional(),
});

/** What the daemon is doing, for the dashboard only. */
export const STATUS_EVENT_STATES = [
  "starting",
  "running",
  "waiting_permission",
  "finishing",
] as const;

/** The daemon's own state for the turn. */
export const StatusEvent = z.strictObject({
  ...envelope,
  type: z.literal("status"),
  state: z.enum(STATUS_EVENT_STATES),
});

/** Every event a daemon reports for a turn. */
export const SessionEvent = z.discriminatedUnion("type", [
  ThoughtEvent,
  ActionEvent,
  ElicitationEvent,
  ResponseEvent,
  ErrorEvent,
  PlanEvent,
  SummaryEvent,
  ExternalUrlEvent,
  UsageEvent,
  StatusEvent,
]);
export type SessionEvent = z.infer<typeof SessionEvent>;

/** `daemon:events`'s body. */
export const EventsRequest = z.strictObject({
  workItemId: z.number().int().positive(),
  events: z.array(SessionEvent).min(1).max(MAX_EVENTS_PER_BATCH),
});
export type EventsRequest = z.infer<typeof EventsRequest>;

/** `daemon:events`'s answer. */
export const EventsResponse = z.looseObject({
  accepted: z.number().int().min(0),
  duplicates: z.number().int().min(0),
  dropped: z.number().int().min(0),
  cancelRequested: z.boolean(),
});
export type EventsResponse = z.infer<typeof EventsResponse>;
